import streamlit as st

st.set_page_config(page_title="ロジスティック方程式分析ツール", layout="wide")


def main():
    """
    Streamlitアプリケーションのメイン関数（トップページ）
    """
    st.title("ロジスティック方程式による時系列データ分析")
    st.markdown(
        """
        ### 概要
        このプロジェクトは、時間経過とともにS字型の成長を示す現象（例：人口増加、製品の普及率など）を分析するための対話的なウェブアプリケーションです。
        ユーザーは時系列データをアップロードし、ロジスティック方程式へのフィッティングを通じて、データに潜む成長パターンを可視化し、将来のトレンドを予測することができます。

        ### 目的
        - **直感的なデータ分析**: プログラミングの知識がないユーザーでも、直感的なUIを通じて高度なデータ分析を実行できるようにする。
        - **動的なパラメータ調整**: モデルのパラメータ（環境収容力 `K` や成長率 `γ`）をリアルタイムで調整し、分析結果への影響を即座に確認できるようにする。
        - **迅速な結果共有**: 分析結果（グラフ、予測データ）を簡単にダウンロードし、レポート作成や情報共有に活用できるようにする。

        ### 使い方
        1.  サイドバーの「分析」ページに移動します。
        2.  **データファイルのアップロード**:
            - 分析したい時系列データを含むExcelファイル（`.xlsx`）をアップロードします。
            - Excelの1列目を時間（例：年）、2列目を観測値（例：人口）としてください。ヘッダーは不要です。
        3.  **パラメータ探索範囲の設定**:
            - **環境収容力 (K)** と **成長率 (γ)** の探索範囲とステップ（刻み幅）を指定します。
            - Kの値が大きい場合は、入力しやすいように単位（万、億、兆）を選択できます。
        4.  **予測期間の設定**:
            - データの開始年と、何年先まで予測したいかを設定します。
        5.  **分析の実行**:
            - 「分析実行」ボタンをクリックすると、パラメータ探索と将来予測が始まります。

        分析が完了すると、ページ内に結果（最適パラメータ、グラフ、予測データ）が表示されます。
        """
    )


if __name__ == "__main__":
    main()
